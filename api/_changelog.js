/**
 * Changelog: what changed in the datasets, and when. Entries are generated —
 * by scripts/changelog.js from git diffs of data files, through each area's
 * changelog.diff(prev, next) (api/_areas/<area>.js), or by a dataset's own
 * build script (scripts/vehicles.js, scripts/software-eol.js) — and annotated
 * by the maintainer (note). what_changed_since reads them.
 *
 * CHANGELOG_AREAS is every area whose module declares `changelog`; the same
 * entries are published for humans and feed readers at /changes, /changes.rss
 * and /changes.atom (api/_changes_render.js) via listEntries.
 */
const CHANGELOG = require('../data/changelog.json');
const { nearest } = require('./_text');
const { BY_KEY, changelogAreas } = require('./_areas');

const COVERAGE_START = '2026-08-31'; // first full verification of every dataset
const CHANGELOG_AREAS = changelogAreas();
const MAX_ENTRIES = 100;

/**
 * The Verified Changes protocol (docs/CHANGES_PROTOCOL.md, served at
 * /protocol): every changes document names the protocol version, the JSON
 * Schema it validates against and its publisher. Discovery document:
 * public/.well-known/changes.json (regenerated by scripts/sync-areas.js).
 */
const PROTOCOL = 'verified-changes/0.1';
const PROTOCOL_BASE = 'https://databutler.dev';
const SCHEMA_URL = `${PROTOCOL_BASE}/schema/changes.v0.json`;
const WELL_KNOWN_URL = `${PROTOCOL_BASE}/.well-known/changes.json`;
const PROTOCOL_URL = `${PROTOCOL_BASE}/protocol`;
const PUBLISHER = { name: 'Data Butler', url: `${PROTOCOL_BASE}/` };

/** The area's diff(prev, next), or null when its entries come from a script. */
function diffFor(area) {
  const a = BY_KEY[area];
  return a && a.changelog ? a.changelog.diff : null;
}

const entryId = (e) => `${e.area}|${e.key}|${e.verifiedDate}`;

/** A bad ?area= or ?since= on the public changelog page/feeds → HTTP 400. */
class ChangelogFilterError extends Error {
  constructor(message, field) {
    super(message);
    this.name = 'ChangelogFilterError';
    this.field = field;
  }
}

const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/;

/**
 * Every entry for the public changelog (page, RSS, Atom), newest first — the
 * whole history, not just "since my cutoff", so it is the read side for humans
 * and feed readers; changesSince stays the agent-facing view. Both filters are
 * optional: area narrows to one dataset area, since keeps entries verified or
 * taking effect after that day. Invalid filters throw ChangelogFilterError.
 */
function listEntries({ area, since } = {}, entries = CHANGELOG) {
  const a = String(area ?? 'all').toLowerCase().trim() || 'all';
  if (a !== 'all' && !CHANGELOG_AREAS.includes(a)) {
    throw new ChangelogFilterError(`unknown area "${area}" — one of ${CHANGELOG_AREAS.join(', ')}, or omit for all`, 'area');
  }
  let s = null;
  if (since !== undefined && since !== null && String(since).trim() !== '') {
    s = String(since).trim();
    if (!ISO_DAY.test(s) || Number.isNaN(Date.parse(s))) {
      throw new ChangelogFilterError(`since must be an ISO date (YYYY-MM-DD), got "${since}"`, 'since');
    }
  }
  return entries
    .filter((e) => (a === 'all' || e.area === a) && (s === null || e.verifiedDate > s || (e.effectiveFrom && e.effectiveFrom > s)))
    .sort((x, y) => String(y.verifiedDate).localeCompare(String(x.verifiedDate)) || String(x.area).localeCompare(String(y.area)) || String(x.key).localeCompare(String(y.key)));
}

function mergeEntries(existing, incoming) {
  const seen = new Set(existing.map(entryId));
  const added = incoming.filter((e) => !seen.has(entryId(e)));
  return { merged: [...existing, ...added], added };
}

/**
 * The agent-facing view (what_changed_since, GET /api/changes): a Verified
 * Changes document — protocol, schema, publisher, generated, entries — plus
 * the query that produced it. `generated` is a day, like every other date in
 * the protocol, so two calls on the same day return identical bytes.
 */
function changesSince({ since, area = 'all' } = {}, entries = CHANGELOG, now = new Date()) {
  const s = String(since || '').slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s) || Number.isNaN(Date.parse(s))) {
    return {
      covered: false, requested: since,
      message: 'since must be an ISO date (YYYY-MM-DD) — typically your training-cutoff date',
      example: { since: '2026-06-01', area: 'all' },
    };
  }
  const a = String(area || 'all').toLowerCase().trim();
  if (a !== 'all' && !CHANGELOG_AREAS.includes(a)) {
    return { covered: false, requested: area, nearest: nearest(a, CHANGELOG_AREAS), areasCovered: CHANGELOG_AREAS };
  }
  const hits = entries
    .filter((e) => (a === 'all' || e.area === a) && (e.verifiedDate > s || (e.effectiveFrom && e.effectiveFrom > s)))
    .sort((x, y) => String(y.verifiedDate).localeCompare(String(x.verifiedDate)))
    .slice(0, MAX_ENTRIES);
  let note;
  if (s < COVERAGE_START) {
    note = `Changelog coverage starts ${COVERAGE_START} (first full verification). Changes between ${s} and ` +
      `${COVERAGE_START} are not itemised — but every figure served was verified on or after ${COVERAGE_START}, ` +
      'so call the lookup tools for current values rather than relying on memory.';
  } else if (hits.length) {
    note = 'Entries newest first: from/to, effectiveFrom, the official source, and a maintainer note where recorded.';
  } else {
    note = `No recorded changes since ${s}. Figures served are current as of their verifiedDate.`;
  }
  return {
    protocol: PROTOCOL, schema: SCHEMA_URL, publisher: PUBLISHER, generated: now.toISOString().slice(0, 10),
    since: s, area: a, coverageStart: COVERAGE_START, areasCovered: CHANGELOG_AREAS, count: hits.length, entries: hits, note,
  };
}

module.exports = {
  changesSince, listEntries, entryId, ChangelogFilterError, diffFor, mergeEntries,
  COVERAGE_START, CHANGELOG_AREAS, PROTOCOL, SCHEMA_URL, WELL_KNOWN_URL, PROTOCOL_URL, PUBLISHER,
};
